"""Tests for independently sourced fixture identity expectations."""

from __future__ import annotations

import hashlib
import json
import unittest

from scripts.android_qualification import fixture_oracle


class FixtureOracleTests(unittest.TestCase):
    def setUp(self) -> None:
        self.identity = {"title": "Example Game", "region": "US"}

    def _identity_digest(self) -> str:
        encoded = json.dumps(
            self.identity, ensure_ascii=False, sort_keys=True, separators=(",", ":")
        ).encode("utf-8")
        return hashlib.sha256(encoded).hexdigest()

    def _independent_evidence(self) -> dict[str, object]:
        return {
            "schema_version": 1,
            "tier": "independent_reference",
            "source": "independent catalog",
            "reference": "catalog-entry:example-game",
            "revision": "2026-10",
            "reference_sha256": "a" * 64,
            "method": "two-source manual comparison",
            "provenance": "Reviewed catalog record and scan report",
            "expected_identity_sha256": self._identity_digest(),
            "limitations": ["No owner ROM corpus supplied"],
            "conflicts": [],
        }

    def test_missing_evidence_does_not_claim_independent_identity(self) -> None:
        assessment = fixture_oracle.assess_identity_evidence(self.identity, None)

        self.assertEqual("not_independently_verified", assessment.identity_support)
        self.assertEqual("not_qualified", assessment.qualification_status)

    def test_synthetic_expectation_is_never_reported_as_independent(self) -> None:
        assessment = fixture_oracle.assess_identity_evidence(
            self.identity,
            {
                "schema_version": 1,
                "tier": "synthetic",
                "provenance": "Generated by a deterministic unit test",
            },
        )

        self.assertEqual("synthetic_only", assessment.identity_support)
        self.assertEqual("not_qualified", assessment.qualification_status)

    def test_independent_reference_is_pinned_but_not_qualified_by_its_hash_alone(self) -> None:
        assessment = fixture_oracle.assess_identity_evidence(
            self.identity, self._independent_evidence()
        )

        self.assertEqual("pinned_unverified", assessment.identity_support)
        self.assertEqual("not_qualified", assessment.qualification_status)

    def test_hash_without_source_and_method_is_not_independent_evidence(self) -> None:
        with self.assertRaises(fixture_oracle.OracleError):
            fixture_oracle.assess_identity_evidence(
                self.identity,
                {"schema_version": 1, "tier": "independent_reference", "reference_sha256": "a" * 64},
            )

    def test_evidence_must_bind_the_expected_game_identity(self) -> None:
        evidence = self._independent_evidence()
        evidence["expected_identity_sha256"] = "b" * 64

        with self.assertRaises(fixture_oracle.OracleError):
            fixture_oracle.assess_identity_evidence(self.identity, evidence)

    def test_evidence_conflicts_are_rejected(self) -> None:
        evidence = self._independent_evidence()
        evidence["conflicts"] = ["Conflicting title in second reference"]

        with self.assertRaises(fixture_oracle.OracleError):
            fixture_oracle.assess_identity_evidence(self.identity, evidence)

    def test_canonical_digest_is_stable_and_rejects_non_json_values(self) -> None:
        self.assertEqual(
            fixture_oracle.canonical_sha256({"region": "US", "title": "Example Game"}),
            fixture_oracle.canonical_sha256(self.identity),
        )
        with self.assertRaises(fixture_oracle.OracleError):
            fixture_oracle.canonical_sha256({"title": float("nan")})

    def test_invalid_identity_and_synthetic_provenance_are_rejected(self) -> None:
        with self.assertRaises(fixture_oracle.OracleError):
            fixture_oracle.assess_identity_evidence([], None)
        for evidence in (
            {"schema_version": True, "tier": "synthetic", "provenance": "unit test"},
            {"schema_version": 1, "tier": "synthetic", "provenance": " "},
            {"schema_version": 1, "tier": "synthetic", "provenance": "unit test", "extra": True},
            {"schema_version": 1, "tier": "unknown"},
        ):
            with self.subTest(evidence=evidence), self.assertRaises(fixture_oracle.OracleError):
                fixture_oracle.assess_identity_evidence(self.identity, evidence)

    def test_independent_reference_fields_and_lists_are_validated(self) -> None:
        bad_text = self._independent_evidence()
        bad_text["source"] = " independent catalog"
        bad_digest = self._independent_evidence()
        bad_digest["reference_sha256"] = "G" * 64
        duplicate_limits = self._independent_evidence()
        duplicate_limits["limitations"] = ["same", "same"]
        bool_version = self._independent_evidence()
        bool_version["schema_version"] = True
        for evidence in (bad_text, bad_digest, duplicate_limits, bool_version):
            with self.subTest(evidence=evidence), self.assertRaises(fixture_oracle.OracleError):
                fixture_oracle.assess_identity_evidence(self.identity, evidence)


if __name__ == "__main__":
    unittest.main()
